# 1. Integer operations
a = 10
b = 3

print("Addition:", a + b)        # 13
print("Subtraction:", a - b)     # 7
print("Multiplication:", a * b)  # 30
print("Division:", a / b)        # 3.333...
print("Modulus:", a % b)         # 1

# 2. Float operations
x = 5.5
y = 2.0

print("Addition:", x + y)        # 7.5
print("Subtraction:", x - y)     # 3.5
print("Multiplication:", x * y)  # 11.0
print("Division:", x / y)        # 2.75
print("Modulus:", x % y)         # 1.5

# 3. String operations
str1 = "Hello"
str2 = "World"

print("Concatenation:", str1 + " " + str2)   # Hello World
print("Repetition:", str1 * 3)               # HelloHelloHello
