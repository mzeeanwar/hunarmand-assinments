# Creating variables of different types
num_int = 10          # int
num_float = 3.14      # float
text_str = "Hello"    # str
flag_bool = True      # bool

# Printing each variable and its type
print(num_int, type(num_int))       # Output: 10 <class 'int'>
print(num_float, type(num_float))   # Output: 3.14 <class 'float'>
print(text_str, type(text_str))     # Output: Hello <class 'str'>
print(flag_bool, type(flag_bool))   # Output: True <class 'bool'>
