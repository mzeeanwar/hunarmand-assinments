# Program: Python Basics Demo

# --- Print “Hello Hunarmand Punjab” ---
print("Hello Hunarmand Punjab")

# --- Declare variables (string, int, float, boolean) ---
name = "Hunarmand"   # string
age = 25             # integer
height = 5.9         # float
is_student = True    # boolean

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is Student:", is_student)

# --- Perform basic arithmetic operations ---
a = 10
b = 3
print("\nArithmetic Operations:")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)

# --- Demonstrate type conversion ---
x = "100"
y = int(x)       # string → int
z = float(y)     # int → float
w = str(z)       # float → string

print("\nType Conversion:")
print("String to Int:", y, type(y))
print("Int to Float:", z, type(z))
print("Float to String:", w, type(w))
