a = 15
b = 4
print(a + b)   # Addition → 19
print(a - b)   # Subtraction → 11
print(a * b)   # Multiplication → 60
print(a / b)   # Division → 3.75
print(a % b)   # Modulus → 3
print(a ** b)  # Exponentiation → 50625
print(a // b)  # Floor division → 3
x = 10
y = 20
print(x == y)   # False
print(x != y)   # True
print(x > y)    # False
print(x < y)    # True
print(x >= 10)  # True
print(y <= 20)  # True
p = True
q = False
print(p and q)   # False
print(p or q)    # True
print(not p)     # False
num = 5
num += 3   # num = num + 3 → 8
num -= 2   # num = num - 2 → 6
num *= 4   # num = num * 4 → 24
num /= 6   # num = num / 6 → 4.0
num %= 3   # num = num % 3 → 1.0
a = 6   # binary: 110
b = 3   # binary: 011
print(a & b)   # AND → 2 (010)
print(a | b)   # OR  → 7 (111)
print(a ^ b)   # XOR → 5 (101)
print(~a)      # NOT → -7
print(a << 1)  # Left shift → 12 (1100)
print(a >> 1)  # Right shift → 3 (011)
