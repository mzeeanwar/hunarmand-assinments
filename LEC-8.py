# 1. Arithmetic Operators
a = 10
b = 3

print("Addition:", a + b)        # + adds two numbers → 13
print("Subtraction:", a - b)     # - subtracts second from first → 7
print("Multiplication:", a * b)  # * multiplies → 30
print("Division:", a / b)        # / divides → 3.333...
print("Modulus:", a % b)         # % gives remainder → 1
print("Floor Division:", a // b) # // divides and rounds down → 3
print("Exponent:", a ** b)       # ** raises power → 1000

# 2. Comparison Operators
x = 5
y = 10

print("Equal:", x == y)          # == checks equality → False
print("Not Equal:", x != y)      # != checks inequality → True
print("Less Than:", x < y)       # < checks if smaller → True
print("Greater Than:", x > y)    # > checks if larger → False
print("Less or Equal:", x <= y)  # <= checks ≤ → True
print("Greater or Equal:", x >= y) # >= checks ≥ → False

# 3. Logical Operators
p = True
q = False

print("AND:", p and q)           # True only if both are True → False
print("OR:", p or q)             # True if at least one is True → True
print("NOT:", not p)             # Flips True to False → False
