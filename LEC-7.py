# Function to calculate area of a rectangle
def calculate_area(length, width):
    return length * width

# Calling the function with different values
print("Area (5 x 3):", calculate_area(5, 3))   # 15
print("Area (10 x 2):", calculate_area(10, 2)) # 20
print("Area (7 x 4):", calculate_area(7, 4))   # 28
